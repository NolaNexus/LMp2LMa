"""Generate STATUS.md from the measured sweep report.

STATUS.md is rank 1 in the truth hierarchy (docs/ROADMAP.md §0): if it and any
other document disagree, it wins. That only holds if it is derived from an
artefact the repo can reproduce, so this script reads the sweep report and the
filesystem and writes the status file. Nothing here is hand-entered.

`tests/test_status_truth.py` independently re-counts the notebooks on disk and
fails when the generated table drifts, which also catches a stale STATUS.md.

Usage:
    python tools/status_report.py            # write STATUS.md
    python tools/status_report.py --stdout   # print instead of writing
"""

import argparse
import datetime as dt
import json
import re
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
REPORT = ROOT / "artifacts" / "execution_report.md"
STATUS = ROOT / "STATUS.md"

# | `track-01-ml-programmer/01_data_preprocessing.ipynb` | PASS | detail |
_RESULT_RE = re.compile(r"^\|\s*`([^`]+\.ipynb)`\s*\|\s*(\w+)\s*\|\s*(.*?)\s*\|\s*$")
_REPORT_META_RE = re.compile(r"^- (Generated|QUICK_MODE):\s*(.+)$", re.MULTILINE)


def track_dirs() -> list[Path]:
    return sorted(p for p in ROOT.glob("track-*") if p.is_dir())


def read_report(path: Path) -> tuple[dict[str, tuple[str, str]], dict[str, str]]:
    """Return ({notebook: (status, detail)}, report metadata)."""
    if not path.exists():
        return {}, {}
    text = path.read_text(encoding="utf-8")
    results = {}
    for line in text.splitlines():
        m = _RESULT_RE.match(line)
        if m:
            results[m.group(1)] = (m.group(2), m.group(3))
    meta = {k: v.strip() for k, v in _REPORT_META_RE.findall(text)}
    return results, meta


def count_notebooks(track: Path) -> int:
    return len(list(track.glob("*.ipynb")))


def count_stored_outputs(track: Path) -> int:
    """Notebooks holding at least one stored output."""
    stored = 0
    for nb in track.glob("*.ipynb"):
        try:
            cells = json.loads(nb.read_text(encoding="utf-8"))["cells"]
        except (json.JSONDecodeError, KeyError):
            continue
        if any(c.get("outputs") for c in cells if c.get("cell_type") == "code"):
            stored += 1
    return stored


def summarise(results):
    by_track = defaultdict(lambda: {"executed": 0, "passed": 0})
    for rel, (status, _detail) in results.items():
        track = rel.split("/", 1)[0]
        by_track[track]["executed"] += 1
        if status == "PASS":
            by_track[track]["passed"] += 1
    return by_track


def render(results, meta, tracks) -> str:
    stamp = dt.datetime.now().isoformat(timespec="seconds")
    by_track = summarise(results)
    measured = len(results)
    total = sum(count_notebooks(t) for t in tracks)

    lines = [
        "# STATUS — measured state",
        "",
        "Generated by `tools/status_report.py`. **Do not hand-edit.**",
        "Rank 1 in the truth hierarchy (`docs/ROADMAP.md` §0): when this file and",
        "any other document disagree, this file wins. `tests/test_status_truth.py`",
        "re-counts the tree and fails on drift.",
        "",
        f"- Generated: {stamp}",
        f"- Interpreter: {sys.version.split()[0]}",
        f"- Sweep report: `{REPORT.relative_to(ROOT)}`"
        + (f" ({meta['Generated']})" if "Generated" in meta else " — **not found**"),
        f"- QUICK_MODE: {meta.get('QUICK_MODE', 'unknown')}",
        f"- Notebooks with a verdict: {measured}/{total}",
        "",
        "## Tracks",
        "",
        "| Track | Notebooks | Executed | Passed | Stored outputs |",
        "|---|---|---|---|---|",
    ]

    for track in tracks:
        name = track.name
        stats = by_track.get(name)
        notebooks = count_notebooks(track)
        executed = str(stats["executed"]) if stats else "not measured"
        passed = str(stats["passed"]) if stats else "—"
        lines.append(
            f"| {name} | {notebooks} | {executed} | {passed} " f"| {count_stored_outputs(track)} |"
        )

    lines += ["", "## Notebooks", ""]
    if results:
        lines += ["| Notebook | Status | First error |", "|---|---|---|"]
        for rel in sorted(results):
            status, detail = results[rel]
            lines.append(f"| `{rel}` | {status} | {detail.replace('|', chr(92) + '|')} |")
    else:
        lines.append("No sweep report found. Run `tools/execution_sweep.py` first.")

    return "\n".join(lines) + "\n"


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--stdout", action="store_true", help="print instead of writing")
    args = parser.parse_args(argv)

    results, meta = read_report(REPORT)
    text = render(results, meta, track_dirs())

    if args.stdout:
        sys.stdout.write(text)
        return 0

    STATUS.write_text(text, encoding="utf-8")
    print(f"Wrote {STATUS.relative_to(ROOT)} ({len(results)} verdicts)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
